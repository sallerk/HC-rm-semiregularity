def holo_diffs(exps, lam):
    """y^5 = prod (x - a_i)^{m_i} (a = 0, 1, lam), gcd(m_i, 5) = 1, total degree D prime to 5: P(x) dx / y^b
    (1 <= b <= 4) is holomorphic iff ord_{a_i} P >= (b m_i - 4)/5 and deg P <= (b D - 6)/5, from the local
    parameters (x - a_i = u^5, y ~ u^{m_i}; at infinity x = u^-5, y ~ u^-D)."""
    x = sympy.Symbol("x")
    pts = [0, 1, lam]
    D = sum(exps)
    assert D % 5 and all(e % 5 for e in exps) and (-D) % 5
    out = []
    for b in range(1, 5):
        c = [max(0, -((4 - b * e) // 5)) for e in exps]          # ceil((b e - 4)/5) clipped at 0
        # at infinity: ord_u (P dx / y^b) = -5 deg P - 6 + b D >= 0
        dmax = (b * D - 6) // 5 if b * D - 6 >= 0 else -1
        free = dmax - sum(c)
        for j in range(free + 1):
            Pb = x ** j * sympy.prod([(x - a) ** ci for a, ci in zip(pts, c)])
            out.append((b, sympy.expand(Pb)))
    return out, x


def quadric(exps):
    lam = sympy.Symbol("lam")
    w, x = holo_diffs(exps, lam)
    g = len(w)
    f = sympy.prod([(x - a) ** e for a, e in zip([0, 1, lam], exps)])
    # products w_i w_j = P_i P_j dx^2 / y^(b_i + b_j); write y^-B = f^-k y^-r, B = 5k + r
    prods, labels = [], []
    for i, j in itertools.combinations_with_replacement(range(g), 2):
        B = w[i][0] + w[j][0]
        k, r = divmod(B, 5)
        prods.append((r, sympy.cancel(w[i][1] * w[j][1] / f ** k)))
        labels.append((i, j))
    # relations: for each r, linear dependencies of the rational functions with that r
    cs = sympy.symbols("c0:%d" % len(prods))
    eqs = []
    for r in range(5):
        expr = sum(c * pr for c, (rr, pr) in zip(cs, prods) if rr == r)
        if expr != 0:
            num = sympy.numer(sympy.together(expr))
            eqs += sympy.Poly(sympy.expand(num), x).coeffs()
    sol = sympy.linsolve(eqs, cs)
    sol = list(sol)[0]
    free = sorted(set().union(*[s.free_symbols for s in sol]) & set(cs), key=str)
    rels = []
    for fs in free:
        vec = [s.subs({ff: (1 if ff == fs else 0) for ff in free}) for s in sol]
        rels.append({labels[i]: sympy.nsimplify(v) for i, v in enumerate(vec) if v != 0})
    return w, rels


