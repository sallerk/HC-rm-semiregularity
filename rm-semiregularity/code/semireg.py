# ----------------------------------------------------------------------------- (Q) mixed quadrics, symmetric points
def kron(D, u):
    """Kronecker symbol (D/u), u > 0."""
    r = 1
    while u % 2 == 0:
        u //= 2
        if D % 2 == 0:
            return 0
        r *= 1 if D % 8 in (1, 7) else -1
    return r * sympy.jacobi_symbol(D % u, u) if u > 1 else r


def real_quad_disc(k):
    """Fundamental discriminants D > 1 with Q(sqrt D) in Q(zeta_k)^+ (i.e. D | k)."""
    out = []
    for D in range(5, k + 1):
        if k % D:
            continue
        if D % 4 == 1 and sympy.factorint(D) and all(e == 1 for e in sympy.factorint(D).values()):
            out.append(D)
        elif D % 4 == 0 and (D // 4) % 4 in (2, 3) and all(e == 1 for e in sympy.factorint(D // 4).values()):
            out.append(D)
    return out


def mixed_conditions(n, W1, W2):
    """phi in End^0(J) commuting with Gamma = Z/n, eigenvalue theta (irrational, real quadratic) on the weight
    lines W1 of H^0(K), theta' on W2.  On the isotypic piece H^1_w the commutant is M_m(Q(zeta_k)) (k = order of w),
    and phi has eigenvalues theta (a_w times) and theta' (b_w times), a_w = #(W1 n {w, -w}).  The characteristic
    polynomial over Q(zeta_k) is Galois-equivariant: if sqrt D is in Q(zeta_k), (a, b) is constant or swapped
    on the class according to the quadratic character (D/u); otherwise a = b.  Returns the D that work."""
    a, b = [0] * n, [0] * n
    for w in W1:
        a[w % n] += 1
        a[(-w) % n] += 1
    for w in W2:
        b[w % n] += 1
        b[(-w) % n] += 1
    classes = {}
    for w in range(n):
        if a[w] + b[w]:
            classes.setdefault(n // math.gcd(w, n), []).append(w)
    for k, lst in classes.items():          # H^1 rational: full Galois classes, constant multiplicity
        if lst != [w for w in range(n) if n // math.gcd(w, n) == k] or len({a[w] + b[w] for w in lst}) != 1:
            return []
    good = []
    for D in sorted(set().union(*[set(real_quad_disc(k)) for k in classes])):
        ok = True
        for k, lst in classes.items():
            if D in real_quad_disc(k):
                u0 = lst[0] // (n // k)
                for w in lst:
                    same = kron(D, w // (n // k)) == kron(D, u0)
                    ok &= (a[w], b[w]) == ((a[lst[0]], b[lst[0]]) if same else (b[lst[0]], a[lst[0]]))
            else:
                ok &= all(a[w] == b[w] for w in lst)
        if ok:
            good.append(D)
    return good


def smooth_33(mons, trials=2):
    """Is the general member of span{x^i y^j : (i, j) in mons} (bidegree (3, 3) on P^1 x P^1) smooth?  Random
    integer members; singular points by Groebner bases in the four affine charts."""
    x, y = sympy.symbols("x y")
    for t in range(trials):
        rng = random.Random(1000 + t)
        cs = [rng.choice([-1, 1]) * rng.randint(1, 97) for _ in mons]
        ok = True
        for fx, fy in itertools.product((0, 1), repeat=2):
            F = sum(c * x ** (3 * fx + (1 - 2 * fx) * i) * y ** (3 * fy + (1 - 2 * fy) * j)
                    for c, (i, j) in zip(cs, mons))
            G = sympy.groebner([F, sympy.diff(F, x), sympy.diff(F, y)], x, y, order="grevlex")
            if list(G.exprs) != [1]:
                ok = False
                break
        if ok:
            return True
    return False


def chevalley_weil(exps, n=5):
    """dim of the zeta^j-eigenspace of tau^* on H^0(K) for y^n = prod (x - a_i)^{e_i} (all branch exponents,
    including infinity, sum = 0 mod n): d_j = -1 + sum_i <-j e_i / n>."""
    return {j: -1 + sum(Fraction((-j * e) % n, n) for e in exps) for j in range(1, n)}


