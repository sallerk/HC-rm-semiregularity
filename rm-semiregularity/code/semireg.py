def moments_ok(meas, q):
    """c = sum n_j exp(L_{h_j}) (F = Q(sqrt 5), h = h0 + h1 sqrt 5) lies in B: the conditions of NOTE 10.5(a)."""
    for kk in range(3):
        for flip in (False, True):
            tot = 0
            for nn, (h0, h1) in meas:
                s1, s2 = h0 + h1 * sympy.sqrt(5), h0 - h1 * sympy.sqrt(5)
                if flip:
                    s1, s2 = s2, s1
                tot += nn * (s1 ** 2 + q) * s2 ** kk
            if sympy.simplify(tot) != 0:
                return False
    return True


def bcoords(meas, q):
    """the coordinates (x, y, z, w) of c in the basis alpha, beta, alpha~, sqrt 5 beta~ (NOTE 10.5(a))."""
    nrm = [h0 * h0 - 5 * h1 * h1 for _, (h0, h1) in meas]
    xx = sum(nn * (1 - nr / q) for (nn, _), nr in zip(meas, nrm)) / 2
    zz = sum(nn * (1 + nr / q) for (nn, _), nr in zip(meas, nrm)) / 2
    return (xx, sum(nn * h[0] for nn, h in meas), zz, sum(nn * h[1] for nn, h in meas))


