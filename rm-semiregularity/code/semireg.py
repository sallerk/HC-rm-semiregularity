def popc(x):
    return bin(x).count("1")


def wedge(a, vec):
    out = {}
    for mk, c in vec.items():
        if mk >> a & 1:
            continue
        s = -1 if popc(mk & ((1 << a) - 1)) & 1 else 1
        k = mk | 1 << a
        out[k] = out.get(k, 0) + s * c
    return {k: v for k, v in out.items() if v != 0}


def contr(a, vec):
    out = {}
    for mk, c in vec.items():
        if not mk >> a & 1:
            continue
        s = -1 if popc(mk & ((1 << a) - 1)) & 1 else 1
        k = mk ^ 1 << a
        out[k] = out.get(k, 0) + s * c
    return {k: v for k, v in out.items() if v != 0}


def ht2(n):
    """basis of HT^2: ('O', a, b) = dzbar_a dzbar_b, ('T', a, b) = dzbar_a d_b, ('L', a, b) = d_a d_b."""
    basis = [("O", a, b) for a, b in itertools.combinations(range(n), 2)]
    basis += [("T", a, b) for a in range(n) for b in range(n)]
    basis += [("L", a, b) for a, b in itertools.combinations(range(n), 2)]
    return basis


def act(x, vec, n):
    """H^1(X, C) basis: dz_j = e_j, dzbar_j = e_{n+j}; d_j = contraction with the dual of dz_j."""
    k, a, b = x
    if k == "O":
        return wedge(n + a, wedge(n + b, vec))
    if k == "T":
        return wedge(n + a, contr(b, vec))
    return contr(a, contr(b, vec))


def act_comb(comb, vec, n):
    out = {}
    for x, cx in comb.items():
        for mk, v in act(x, vec, n).items():
            out[mk] = out.get(mk, 0) + cx * v
    return {k: v for k, v in out.items() if v != 0}


def poly(n, coef):
    """sum coef[(i, j)] Omega_1^i Omega_2^j, Omega_k = sum_{j in block k} dz_j dzbar_j; coefficients any ring."""
    m = n // 2
    vec = {}
    for S in range(1 << n):
        i, j = popc(S & ((1 << m) - 1)), popc(S >> m)
        c = coef.get((i, j), 0)
        if c == 0:
            continue
        cur = {0: 1}
        for l in range(n):
            if S >> l & 1:
                cur = wedge(n + l, wedge(l, cur))
        for mk, cc in cur.items():
            vec[mk] = vec.get(mk, 0) + c * math.factorial(i) * math.factorial(j) * cc
    return {k: v for k, v in vec.items() if v != 0}


def series(n, e1, e2, f):
    """coefficients of sum_k f_k (e1 Omega_1 + e2 Omega_2)^k."""
    m = n // 2
    coef = {}
    for k, fk in f.items():
        for i in range(k + 1):
            j = k - i
            if i <= m and j <= m:
                coef[(i, j)] = coef.get((i, j), 0) + fk * math.comb(k, i) * e1 ** i * e2 ** j
    return coef


def b_basis(n, q):
    """rational basis alpha, beta, alpha~, beta~ of B (Omega frame), exact Fractions."""
    cosf = {k: Fraction((-q) ** (k // 2), math.factorial(k)) for k in range(0, n + 1, 2)}
    sinf = {k: Fraction((-q) ** (k // 2), math.factorial(k)) for k in range(1, n + 1, 2)}
    return [poly(n, series(n, e1, e2, f)) for e1, e2 in ((1, 1), (1, -1)) for f in (cosf, sinf)]


# ----------------------------------------------------------------------------- modular ranks (upper bounds on K)
class Mod:
    """the ring hom Z[1/N][sqrt t] -> F_p, sqrt t -> s."""

    def __init__(self, p, t):
        self.p = p
        self.s = sqrt_mod(t % p, p)

    def red(self, x):
        """x: Fraction, int, or pair (a, b) meaning a + b sqrt t."""
        p = self.p
        if isinstance(x, tuple):
            return (self.red(x[0]) + self.s * self.red(x[1])) % p
        x = Fraction(x)
        return x.numerator % p * pow(x.denominator % p, p - 2, p) % p


def sqrt_mod(a, p):
    a %= p
    if a == 0:
        return 0
    if pow(a, (p - 1) // 2, p) != 1:
        return None
    return int(sympy.ntheory.residue_ntheory.sqrt_mod(a, p))


def rank_mod(cols, p):
    """rank over F_p of the matrix whose columns are the dicts cols (row key -> residue)."""
    keys = sorted(set(k for c in cols for k in c))
    if not keys:
        return 0
    idx = {k: i for i, k in enumerate(keys)}
    A = np.zeros((len(cols), len(keys)), dtype=np.int64)
    for i, c in enumerate(cols):
        for k, v in c.items():
            A[i, idx[k]] = v % p
    r = 0
    rows, ncol = A.shape
    for j in range(ncol):
        piv = None
        for i in range(r, rows):
            if A[i, j]:
                piv = i
                break
        if piv is None:
            continue
        A[[r, piv]] = A[[piv, r]]
        inv = pow(int(A[r, j]), p - 2, p)
        A[r] = A[r] * inv % p
        for i in range(rows):
            if i != r and A[i, j]:
                A[i] = (A[i] - A[i, j] * A[r]) % p
        r += 1
        if r == rows:
            break
    return r


def columns(n, classes, basis, md):
    """the classes are first reduced modulo p (coefficients Fractions or pairs a + b sqrt t)."""
    red = [{k: md.red(v) for k, v in c.items()} for c in classes]
    cols = []
    for x in basis:
        col = {}
        for ci, c in enumerate(red):
            for mk, v in act(x, c, n).items():
                if v % md.p:
                    col[(ci, mk)] = v % md.p
        cols.append(col)
    return cols


def kerdim_mod(n, classes, md, kinds=None):
    basis = [x for x in ht2(n) if kinds is None or x[0] in kinds]
    return len(basis) - rank_mod(columns(n, classes, basis, md), md.p)


# ----------------------------------------------------------------------------- explicit kernels (lower bounds)
def rm_basis(n):
    m = n // 2
    out = []
    for blk in (range(m), range(m, n)):
        for a, b in itertools.combinations_with_replacement(blk, 2):
            out.append({("T", a, b): 1, ("T", b, a): 1} if a != b else {("T", a, a): 1})
    return out


def sym_basis(n):
    return [{("T", a, b): 1, ("T", b, a): 1} if a != b else {("T", a, a): 1}
            for a, b in itertools.combinations_with_replacement(range(n), 2)]


def gerby_basis(n, q, pairs):
    return [{("O", a, b): 1, ("L", a, b): Fraction(1, q)} for a, b in pairs]


def annihilates(n, comb, classes):
    return all(not act_comb(comb, c, n) for c in classes)


def indep(combs, n):
    basis = {x: i for i, x in enumerate(ht2(n))}
    M = sympy.Matrix([[c.get(x, 0) for x in basis] for c in combs])
    return M.rank() == len(combs)


