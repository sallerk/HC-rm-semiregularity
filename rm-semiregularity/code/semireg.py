def flattening_ranks(m, coef):
    """rank of contraction with c on HT^k, k = 0..4m (zero beyond 2m), by the block formula of (G);
    coef[(a, b)] = c_{a,b}."""
    out = []
    for k in range(4 * m + 1):
        tot = 0
        for u in range(0, min(k, m) + 1):
            v = k - u
            if v > m:
                continue
            rows = [(i, j) for i in range(u + 1) for j in range(v + 1)]
            cols = [(i, j) for i in range(m - u + 1) for j in range(m - v + 1)]
            N = sympy.Matrix(len(rows), len(cols),
                             lambda r, s_: coef[(rows[r][0] + cols[s_][0], rows[r][1] + cols[s_][1])])
            tot += math.comb(m, u) * math.comb(m, v) * N.rank(simplify=True)
        out.append(tot)
    return out


def direct_ranks(n, c, md):
    W = [("w", n + j) for j in range(n)] + [("c", j) for j in range(n)]
    red = {k: md.red(v) for k, v in c.items()}
    out = []
    for k in range(2 * n + 1):
        cols = []
        for combo in itertools.combinations(W, k):
            vec = red
            for kind, a in reversed(combo):
                vec = wedge(a, vec) if kind == "w" else contr(a, vec)
                if not vec:
                    break
            cols.append({m_: v % md.p for m_, v in vec.items() if v % md.p})
        out.append(rank_mod(cols, md.p))
    return out


