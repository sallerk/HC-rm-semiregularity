def check_D():
    q, s1, s2, T1, T2, x = sympy.symbols("q s1 s2 T1 T2 x")

    def red(e):
        P_ = sympy.Poly(sympy.expand(e), T1, T2)
        return sum(c * T1 ** i * T2 ** j for (i, j), c in P_.terms() if i <= 2 and j <= 2)

    def integ(e):
        return sympy.Poly(red(e), T1, T2).coeff_monomial(T1 ** 2 * T2 ** 2) * 4

    def tau(e):
        P_ = sympy.Poly(red(e), T1, T2)
        return sum(c * (-1) ** (i + j) * T1 ** i * T2 ** j for (i, j), c in P_.terms())

    def mukai(u, v):
        return sympy.simplify(integ(tau(u) * v))

    def ser(f, X):
        return sum(f.diff(x, k).subs(x, 0) / sympy.factorial(k) * X ** k for k in range(5))

    cosq, sinq = sympy.cos(sympy.sqrt(q) * x), sympy.sin(sympy.sqrt(q) * x) / sympy.sqrt(q)
    basis = [red(ser(f, X)) for X in (T1 + T2, T1 - T2) for f in (cosq, sinq)]
    G = sympy.Matrix(4, 4, lambda i, j: mukai(basis[i], basis[j]))
    ok = G == sympy.diag(8 * q ** 2, 8 * q, 8 * q ** 2, 8 * q)
    bg = s1 * T1 + s2 * T2 - q / 2 * T1 * T2 * (s2 * T1 + s1 * T2)
    chi_bg = sympy.factor(mukai(bg, bg))
    ok &= sympy.simplify(chi_bg - 4 * q * (s1 ** 2 + s2 ** 2)) == 0
    print("    (D) Gram matrix of alpha, beta, alpha~, beta~: %s; (b_g, b_g) = %s: %s" % (list(G), chi_bg, ok))
    return {"gram": str(G), "chi_b_g": str(chi_bg)}, bool(ok)


def ann_ht1(n, c, md):
    red = {k: md.red(v) for k, v in c.items()}
    cols = []
    for op in [("w", n + j) for j in range(n)] + [("c", j) for j in range(n)]:
        out = wedge(op[1], red) if op[0] == "w" else contr(op[1], red)
        cols.append({k: v % md.p for k, v in out.items() if v % md.p})
    return 2 * n - rank_mod(cols, md.p)


