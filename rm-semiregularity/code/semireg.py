    # no fixed plane: mu -> -1/conj(mu) (first ruling), nu -> -1/conj(nu) (second).
    re_, im_ = sympy.symbols("re im", real=True)
    m = re_ + sympy.I * im_
    S = sympy.diag(1, 1, 1, -1)                 # w-coordinates <-> w'-coordinates
    def conj_vec(v):
        c = S * v
        c = sympy.Matrix([sympy.conjugate(c[3]), sympy.conjugate(c[2]), sympy.conjugate(c[1]),
                          sympy.conjugate(c[0])])
        return S * c
    rulings = {"first": sympy.Matrix([[1, 0], [0, 1], [-m, 0], [0, -m]]),
               "second": sympy.Matrix([[1, 0], [-m, 0], [0, 1], [0, -m]])}
    real_ok = True
    for nm, R in rulings.items():
        Rc = sympy.Matrix.hstack(conj_vec(R[:, 0]), conj_vec(R[:, 1]))
        target = R.subs({re_: -re_ / (re_ ** 2 + im_ ** 2), im_: -im_ / (re_ ** 2 + im_ ** 2)}, simultaneous=True)
        # same plane: rank of [Rc | target] is 2
        st = sympy.simplify(sympy.Matrix.hstack(Rc, target) * (re_ ** 2 + im_ ** 2))
        real_ok &= st.rank(simplify=True) == 2
    # E has no CM: for p = 1 mod 5, F_20 is defined over F_p, so a_p(C) = 4 a_p(E); two ordinary primes with
    # different fields Q(sqrt(a_p^2 - 4p)) exclude CM.
    aps = {}
    for pr in (11, 31, 41, 61, 71, 101):
        fifth = {pow(t, 5, pr) for t in range(1, pr)}
        cnt = 4 + 5 * sum(1 for t in range(pr) if t not in (0, 1, pr - 1)
                          and t * (t - 1) ** 2 * (t + 1) ** 3 % pr in fifth)
        aps[pr] = pr + 1 - cnt
    sqf = {pr: sympy.sqrt(sympy.Integer((ap // 4) ** 2 - 4 * pr)).as_coeff_Mul()[1] for pr, ap in aps.items()}
    cm_ok = (all(ap % 4 == 0 and (ap // 4) ** 2 <= 4 * pr and (ap // 4) % pr for pr, ap in aps.items())
             and sqf[11] != sqf[31])
    ok3 = psi_ok and swap_ok and inv_ok and real_ok and cm_ok
    ok &= ok3
    res["bring"] = {"psi": {b: list(map(str, v)) for b, v in img.items()}, "a_p(C)": aps,
                    "a_p(E)": {k: v // 4 for k, v in aps.items()}, "fields": {k: str(v) for k, v in sqf.items()}}
    print("    (Q) lambda = -1: psi^* w_b = %s, Q invariant %s, rulings swapped %s, real structure fixes no plane "
          "of either ruling %s; a_p(E) = %s, Q(sqrt(a_p^2 - 4p)) = %s: %s"
          % ({b: v for b, v in img.items()}, inv_ok, swap_ok, real_ok, {k: v // 4 for k, v in aps.items()},
             {k: str(v) for k, v in sqf.items()}, ok3), flush=True)
    return res, ok


